function createMajorBoss({
  id,
  name,
  level,
  biomeId,
  visualVariant = "default",
  baseHp,
  armor,
  resistances = {},
  weaknesses = {},
  motif,
  behavior,
  palette,
  guard,
  attacks,
}) {
  return {
    id,
    name,
    level,
    biomeId,
    visualVariant,
    baseHp,
    hitbox: {
      x: 236,
      y: 64,
      width: 488,
      height: 164,
    },
    armor,
    resistances,
    weaknesses,
    phaseThresholds: [
      {
        phase: 2,
        hpRatio: 0.66,
        armorBonus: 1,
      },
      {
        phase: 3,
        hpRatio: 0.33,
        armorBonus: 2,
      },
    ],
    attacks,
    summons: {
      guardBrick: {
        type: "boss_summon",
        width: guard.width,
        height: guard.height,
        hp: guard.hp,
        armor: guard.armor,
        requiredForClear: false,
        palette: { fill: guard.fill, accent: guard.accent },
      },
    },
    behavior,
    visual: { motif },
    palette,
    assetIdle: `boss_${id}`,
    assetDamaged: `boss_${id}`,
  };
}
